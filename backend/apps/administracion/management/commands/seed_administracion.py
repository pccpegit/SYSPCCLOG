class Command(BaseCommand):
    help = 'Seed proveedores de pasajes and politicas de devolucion from legacy data'

    @transaction.atomic
    def handle(self, *args, **options):
        from apps.administracion.models import ProveedorPasajes, PoliticaPasajeDevoluciones

        self.stdout.write(self.style.MIGRATE_HEADING('\n=== Seeding Administracion Data ===\n'))

        # ── Proveedores ──
        prov_created = 0
        seen_rucs = set()
        for line in PROVEEDORES_RAW.strip().split('\n'):
            parts = line.split(',', 1)
            if len(parts) != 2:
                continue
            ruc = parts[0].strip()
            razon = parts[1].strip()
            if not ruc or ruc in seen_rucs:
                continue
            seen_rucs.add(ruc)
            _, created = ProveedorPasajes.objects.get_or_create(
                ruc=ruc,
                defaults={'razon_social': razon},
            )
            if created:
                prov_created += 1

        self.stdout.write(self.style.SUCCESS(f'  Proveedores: {prov_created} created ({len(seen_rucs)} unique RUCs)'))

        # ── Politicas Worker ──
        pol_created = 0
        for (no_dev, en_dol, tramo, monto_dol, monto_sol) in POLITICAS_WORKER:
            _, created = PoliticaPasajeDevoluciones.objects.get_or_create(
                tipo_trabajador='WORKER',
                tramo=tramo,
                defaults={
                    'en_dolares': en_dol,
                    'no_devolucion': no_dev,
                    'monto_dolares': Decimal(str(monto_dol)),
                    'monto_soles': Decimal(str(monto_sol)),
                },
            )
            if created:
                pol_created += 1

        # ── Politicas Staff ──
        for (no_dev, en_dol, tramo, monto_dol, monto_sol) in POLITICAS_STAFF:
            _, created = PoliticaPasajeDevoluciones.objects.get_or_create(
                tipo_trabajador='STAFF',
                tramo=tramo,
                defaults={
                    'en_dolares': en_dol,
                    'no_devolucion': no_dev,
                    'monto_dolares': Decimal(str(monto_dol)),
                    'monto_soles': Decimal(str(monto_sol)),
                },
            )
            if created:
                pol_created += 1

        self.stdout.write(self.style.SUCCESS(f'  Politicas: {pol_created} created'))
        self.stdout.write(self.style.SUCCESS('\nSeed completed.\n'))
