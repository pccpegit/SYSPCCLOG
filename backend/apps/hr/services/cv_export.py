"""ZIP (streaming) and Excel (write_only) exports of a CV analysis (SYSPCC-023).

Excel is generated by the backend (documented exception to the "ExcelJS in the
frontend" rule): same download path as the PDF/ZIP, the JSONs with PII never
travel to the browser just to build a file, and the formula neutralization is
testable in one place.
"""

import io
import re
import unicodedata
import zipfile
from datetime import datetime

from django.db.models import F
from django.utils import timezone
from openpyxl import Workbook
from openpyxl.cell import WriteOnlyCell
from openpyxl.styles import Font

from apps.hr.enums import CVItemStatus, CVRecommendation
from apps.hr.models import CVAnalysisItem
from apps.hr.services import cv_report_pdf

MAX_CELL_CHARS = 32_000
_FORMULA_START = ('=', '+', '-', '@', '\t', '\r')
_ILLEGAL = re.compile(r'[\x00-\x08\x0b\x0c\x0e-\x1f]')
REQ_LABEL = {'met': 'Cumple', 'partial': 'Parcial', 'not_met': 'No cumple', 'unknown': 'Sin información'}
REC_LABEL = {r.value: str(r.label) for r in CVRecommendation}
ZIP_CHUNK = 64 * 1024


# ----------------------------------------------------------------- helpers

def ascii_slug(text: str, default: str = 'cv', limit: int = 40) -> str:
    text = unicodedata.normalize('NFKD', text or '').encode('ascii', 'ignore').decode()
    text = re.sub(r'[^A-Za-z0-9]+', '-', text).strip('-')
    return (text or default)[:limit].strip('-') or default


def today_stamp() -> str:
    return timezone.localdate().strftime('%Y%m%d')


def xlsx_filename(analysis) -> str:
    return f'Candidatos_{ascii_slug(analysis.name, "analisis")}_{today_stamp()}.xlsx'


def zip_filename(analysis) -> str:
    return f'CVs_{ascii_slug(analysis.name, "analisis")}_{today_stamp()}.zip'


def report_filename(item) -> str:
    surname = ascii_slug((item.candidate_name or '').split(',')[0].split(' ')[0], 'Candidato', 30)
    return f'Reporte_{surname}_{item.pk}.pdf'


def safe_text(value) -> str:
    """Neutralize spreadsheet formulas (CSV/Excel injection) and illegal chars."""
    text = '' if value is None else str(value)
    text = _ILLEGAL.sub('', text)[:MAX_CELL_CHARS]
    if text.lstrip().startswith(_FORMULA_START) or text.startswith(_FORMULA_START):
        text = "'" + text
    return text


def safe_cell(ws, value, bold: bool = False):
    """Text cell forced to string type; numbers are written as numbers."""
    if isinstance(value, bool):
        value = 'Sí' if value else 'No'
    if value is None:
        value = ''
    if isinstance(value, (int, float)):
        cell = WriteOnlyCell(ws, value=value)
    else:
        cell = WriteOnlyCell(ws, value=safe_text(value))
        cell.data_type = 's'
    if bold:
        cell.font = Font(bold=True)
    return cell


# ------------------------------------------------------------------- Excel

def ranked_done_items(analysis):
    """DONE items ordered as the ranking (score desc, years desc, name)."""
    return list(
        analysis.items.filter(status=CVItemStatus.DONE).order_by(
            F('score').desc(nulls_last=True), F('experience_years').desc(nulls_last=True),
            'candidate_name', 'position',
        )
    )


def compute_ranks(items) -> dict[int, int]:
    """Competition ranking by score (ties share the rank)."""
    ranks, prev, rank = {}, object(), 0
    scored = [i for i in items if i.score is not None]
    scored.sort(key=lambda i: -i.score)
    for pos, it in enumerate(scored, start=1):
        if it.score != prev:
            rank, prev = pos, it.score
        ranks[it.pk] = rank
    return ranks


def build_xlsx(analysis) -> bytes:
    items = ranked_done_items(analysis)
    failed = list(analysis.items.filter(status=CVItemStatus.FAILED).order_by('position'))
    ranks = compute_ranks(items)
    wb = Workbook(write_only=True)

    ws = wb.create_sheet('Candidatos')
    ws.freeze_panes = 'A2'
    headers = ['Ranking', 'Nombre', 'Correo', 'Teléfono', 'Ubicación', 'Titular', 'Años exp.',
               'Formación principal', 'Habilidades', 'Idiomas', 'Puntaje', 'Sugerencia',
               'Fortalezas', 'Brechas', 'Archivo original']
    for letter, width in zip('ABCDEFGHIJKLMNO', (9, 28, 28, 16, 20, 30, 10, 36, 40, 24, 9, 14, 45, 45, 30)):
        ws.column_dimensions[letter].width = width
    ws.append([safe_cell(ws, h, bold=True) for h in headers])
    for it in items:
        rep = (it.result or {}).get('report') or {}
        cand = rep.get('candidate') or {}
        edu = (rep.get('education') or [{}])[0]
        evaluation = rep.get('evaluation') or {}
        years = ((it.result or {}).get('computed') or {}).get('experience_years')
        ws.append([
            safe_cell(ws, ranks.get(it.pk, '')), safe_cell(ws, it.candidate_name or cand.get('full_name')),
            safe_cell(ws, cand.get('email')), safe_cell(ws, cand.get('phone')),
            safe_cell(ws, cand.get('location')), safe_cell(ws, it.headline),
            safe_cell(ws, float(years) if years is not None else ''),
            safe_cell(ws, ' - '.join(x for x in (edu.get('degree'), edu.get('institution')) if x)),
            safe_cell(ws, ', '.join(rep.get('skills') or [])),
            safe_cell(ws, ', '.join(lang.get('language', '') for lang in rep.get('languages') or [])),
            safe_cell(ws, it.score if it.score is not None else ''),
            safe_cell(ws, REC_LABEL.get(it.recommendation, '')),
            safe_cell(ws, '\n'.join(evaluation.get('strengths') or [])),
            safe_cell(ws, '\n'.join(evaluation.get('gaps') or [])),
            safe_cell(ws, it.original_name),
        ])
    ws.auto_filter.ref = f'A1:O{len(items) + 1}'

    if analysis.requirements:
        wr = wb.create_sheet('Requisitos')
        wr.freeze_panes = 'B2'
        wr.append([safe_cell(wr, 'Candidato', bold=True)] + [
            safe_cell(wr, f'{r["id"]}. {r["text"]}' + (' (obligatorio)' if r['weight'] > 1 else ''), bold=True)
            for r in analysis.requirements])
        for it in items:
            by_id = {r['id']: r for r in ((it.result or {}).get('computed') or {}).get('requirements') or []}
            wr.append([safe_cell(wr, it.candidate_name or it.original_name)] + [
                safe_cell(wr, REQ_LABEL.get((by_id.get(r['id']) or {}).get('status'), 'Sin información'))
                for r in analysis.requirements])

    we = wb.create_sheet('Con error')
    we.append([safe_cell(we, 'Archivo', bold=True), safe_cell(we, 'Motivo', bold=True)])
    for it in failed:
        we.append([safe_cell(we, it.original_name), safe_cell(we, it.error_message)])

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


# --------------------------------------------------------------------- ZIP

class _StreamBuffer:
    """Non-seekable sink: zipfile writes here and we drain it in chunks, so
    memory is O(chunk) and not O(archive). No `seek` -> zipfile uses data
    descriptors."""

    def __init__(self):
        self._chunks: list[bytes] = []
        self._pos = 0

    def write(self, data):
        self._chunks.append(bytes(data))
        self._pos += len(data)
        return len(data)

    def tell(self):
        return self._pos

    def flush(self):
        pass

    def drain(self) -> bytes:
        data, self._chunks = b''.join(self._chunks), []
        return data


def report_bytes(item) -> bytes:
    """Stored report if present, else regenerated from the JSON."""
    if item.report_pdf:
        try:
            with item.report_pdf.open('rb') as fh:
                return fh.read()
        except (FileNotFoundError, OSError, ValueError):
            pass
    return cv_report_pdf.build(item)


def zip_entry_name(index: int, item) -> str:
    return f'{index:03d}_{ascii_slug(item.candidate_name, "candidato", 40)}_{item.pk:08x}.pdf'


def stream_zip(analysis, item_ids: list[int], include_summary: bool = True):
    """Generator of bytes. One PDF at a time; items are re-fetched by id."""
    sink = _StreamBuffer()
    zf = zipfile.ZipFile(sink, 'w', zipfile.ZIP_DEFLATED)

    def add(name: str, data: bytes):
        info = zipfile.ZipInfo(name, date_time=datetime.now().timetuple()[:6])
        info.compress_type = zipfile.ZIP_DEFLATED
        with zf.open(info, 'w') as dest:
            for off in range(0, len(data), ZIP_CHUNK):
                dest.write(data[off:off + ZIP_CHUNK])
                chunk = sink.drain()
                if chunk:
                    yield chunk

    try:
        if include_summary:
            yield from add('Resumen.xlsx', build_xlsx(analysis))
        for index, item_id in enumerate(item_ids, start=1):
            item = CVAnalysisItem.objects.select_related('analysis').filter(
                pk=item_id, analysis=analysis, status=CVItemStatus.DONE).first()
            if item is None:  # deleted while streaming
                continue
            yield from add(zip_entry_name(index, item), report_bytes(item))
    finally:
        zf.close()
    tail = sink.drain()
    if tail:
        yield tail
